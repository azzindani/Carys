// Generate the vendored OME-Zarr sample store (deterministic, no randomness,
// no timestamps — rerunning yields byte-identical output). Layout mirrors the
// in-app synthetic demo (CellsView demoFetch) at 2x size with a real pyramid:
//   samples/cells_demo.zarr/
///.zgroup, .zattrs (multiscales c,z,y,x → datasets 0,1)
//    0/.zarray + 8 raw chunks   (L0: 2ch x 1z x 128x128, chunks 1x1x64x64)
//    1/.zarray + 2 gzip chunks  (L1: 2ch x 1z x 64x64, floor-mean of L0)
// Channel 0 reads as nuclei-like blobs, channel 1 as a membrane-like ring.
// Run: npm run gen:cells
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'samples', 'cells_demo.zarr');
const N = 128, CH = 64;

function pixel(c, x, y) {
  const blob = (cx, cy, s) => {
    const d2 = (x - cx) * (x - cx) + (y - cy) * (y - cy);
    return 255 * Math.exp(-d2 / (2 * s * s));
  };
  if (c === 0) return Math.min(255, Math.round(blob(40, 44, 14) + blob(88, 80, 18) + 8));
  const r = Math.hypot(x - 64, y - 64);
  return Math.min(255, Math.round(220 * Math.exp(-((r - 40) ** 2) / 72) + 8));
}

const json = (o) => JSON.stringify(o, null, 2);
const w = (rel, data) => {
  const p = join(OUT, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
};

w('.zgroup', json({ zarr_format: 2 }));
w('.zattrs', json({
  multiscales: [{
    version: '0.4',
    name: 'cells_demo',
    axes: [{ name: 'c', type: 'channel' }, { name: 'z', type: 'space' }, { name: 'y', type: 'space' }, { name: 'x', type: 'space' }],
    datasets: [{ path: '0' }, { path: '1' }],
    type: 'mean',
    metadata: { description: 'synthetic nuclei+ring, generated by scripts/gen-cells-zarr.mjs' },
  }],
}));

// L0 full-res pixels, retained to downsample L1
const full = [];
for (let c = 0; c < 2; c++) {
  full.push([]);
  for (let cy = 0; cy < 2; cy++) {
    for (let cx = 0; cx < 2; cx++) {
      const bytes = Buffer.alloc(CH * CH);
      for (let y = 0; y < CH; y++) {
        for (let x = 0; x < CH; x++) bytes[y * CH + x] = pixel(c, cx * CH + x, cy * CH + y);
      }
      full[c].push(bytes);
    }
  }
}
w('0/.zarray', json({
  zarr_format: 2, shape: [2, 1, N, N], chunks: [1, 1, CH, CH],
  dtype: '|u1', compressor: null, fill_value: 0, order: 'C', filters: null,
}));
for (let c = 0; c < 2; c++) {
  for (let cy = 0; cy < 2; cy++) {
    for (let cx = 0; cx < 2; cx++) w(`0/${c}.0.${cy}.${cx}`, full[c][cy * 2 + cx]);
  }
}

// L1: floor-mean 2x2 downsample, gzip chunks (exercises the compressed path)
const at = (c, x, y) => {
  const cx = Math.floor(x / CH), cy = Math.floor(y / CH);
  return full[c][cy * 2 + cx][(y % CH) * CH + (x % CH)];
};
const small = [];
for (let c = 0; c < 2; c++) {
  const px = Buffer.alloc((N / 2) * (N / 2));
  for (let y = 0; y < N / 2; y++) {
    for (let x = 0; x < N / 2; x++) {
      px[y * (N / 2) + x] = Math.floor((at(c, 2 * x, 2 * y) + at(c, 2 * x + 1, 2 * y) + at(c, 2 * x, 2 * y + 1) + at(c, 2 * x + 1, 2 * y + 1)) / 4);
    }
  }
  small.push(px);
}
w('1/.zarray', json({
  zarr_format: 2, shape: [2, 1, N / 2, N / 2], chunks: [1, 1, N / 2, N / 2],
  dtype: '|u1', compressor: { id: 'gzip', level: 5 }, fill_value: 0, order: 'C', filters: null,
}));
for (let c = 0; c < 2; c++) w(`1/${c}.0.0.0`, gzipSync(small[c]));

// fingerprints for the test goldens (mean/min/max per channel/level + spots)
const stats = (buf) => {
  let min = 255, max = 0, sum = 0;
  for (const v of buf) {
    if (v < min) min = v;
    if (v > max) max = v;
    sum += v;
  }
  return { min, max, mean: sum / buf.length };
};
console.log(JSON.stringify({
  L0c0: stats(Buffer.concat(full[0])),
  L0c1: stats(Buffer.concat(full[1])),
  L1c0: stats(small[0]),
  L1c1: stats(small[1]),
  spots: {
    L0c0_0_0: full[0][0][0], L0c0_127_127: full[0][3][CH * CH - 1],
    L0c1_64_64: full[1][3][0], L1c0_0_0: small[0][0], L1c1_32_32: small[1][32 * 64 + 32],
  },
}, null, 1));
